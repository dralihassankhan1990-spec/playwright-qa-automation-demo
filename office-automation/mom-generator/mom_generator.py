#!/usr/bin/env python3
"""
Meeting Minutes (MOM) Generator
================================
Generates a professional, print-ready Minutes-of-Meeting Word document
(.docx) from a simple JSON input file.

Usage:
    python mom_generator.py sample_meeting.json
    python mom_generator.py my_meeting.json -o minutes_oct.docx

JSON schema:
{
  "title": "Weekly Project Review",
  "date": "2026-10-12",
  "time": "10:00 AM - 11:00 AM",
  "venue": "Conference Room B / Teams",
  "attendees": ["Ayesha Khan (Chair)", "Bilal Ahmed", ...],
  "agenda": [
    {"topic": "Sprint progress", "discussion": ["..."], "decisions": ["..."]},
    ...
  ],
  "actions": [
    {"task": "...", "owner": "...", "due": "2026-10-20"},
    ...
  ]
}
"""
import json
import sys
from datetime import datetime
from docx import Document
from docx.shared import Pt, Inches, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT

ACCENT = RGBColor(0x1F, 0x4E, 0x79)


def add_heading_styled(doc, text, level=1):
    h = doc.add_heading(text, level=level)
    for run in h.runs:
        run.font.color.rgb = ACCENT
    return h


def generate(data: dict, out_path: str):
    doc = Document()

    # Title block
    title = doc.add_heading(data.get("title", "Meeting Minutes"), level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub = doc.add_paragraph()
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = sub.add_run("Minutes of Meeting")
    run.font.size = Pt(13)
    run.font.color.rgb = ACCENT

    # Meta table
    meta = [
        ("Date", data.get("date", "")),
        ("Time", data.get("time", "")),
        ("Venue", data.get("venue", "")),
        ("Attendees", ", ".join(data.get("attendees", []))),
    ]
    table = doc.add_table(rows=len(meta), cols=2)
    table.style = "Light Grid Accent 1"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, (k, v) in enumerate(meta):
        table.cell(i, 0).text = k
        table.cell(i, 1).text = v
        for p in table.cell(i, 0).paragraphs:
            for r in p.runs:
                r.bold = True

    # Agenda / discussion
    add_heading_styled(doc, "Discussion & Decisions", level=1)
    for idx, item in enumerate(data.get("agenda", []), start=1):
        doc.add_heading(f"{idx}. {item.get('topic', '')}", level=2)
        for point in item.get("discussion", []):
            doc.add_paragraph(point, style="List Bullet")
        for decision in item.get("decisions", []):
            p = doc.add_paragraph(style="List Bullet")
            run = p.add_run("Decision: ")
            run.bold = True
            p.add_run(decision)

    # Action items
    add_heading_styled(doc, "Action Items", level=1)
    actions = data.get("actions", [])
    if actions:
        at = doc.add_table(rows=1 + len(actions), cols=4)
        at.style = "Light Grid Accent 1"
        at.alignment = WD_TABLE_ALIGNMENT.CENTER
        for j, h in enumerate(["#", "Action", "Owner", "Due Date"]):
            cell = at.cell(0, j)
            cell.text = h
            for p in cell.paragraphs:
                for r in p.runs:
                    r.bold = True
        for i, a in enumerate(actions, start=1):
            at.cell(i, 0).text = str(i)
            at.cell(i, 1).text = a.get("task", "")
            at.cell(i, 2).text = a.get("owner", "")
            at.cell(i, 3).text = a.get("due", "")
    else:
        doc.add_paragraph("No action items recorded.")

    # Footer
    doc.add_paragraph()
    foot = doc.add_paragraph()
    foot.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = foot.add_run(
        f"Generated by Office Automation Toolkit — {datetime.now():%Y-%m-%d %H:%M}"
    )
    run.font.size = Pt(8)
    run.font.color.rgb = RGBColor(0x99, 0x99, 0x99)

    doc.save(out_path)
    print(f"Saved: {out_path}")


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    src = sys.argv[1]
    out = sys.argv[3] if len(sys.argv) > 3 and sys.argv[2] == "-o" else "meeting_minutes.docx"
    with open(src, encoding="utf-8") as f:
        generate(json.load(f), out)


if __name__ == "__main__":
    main()
